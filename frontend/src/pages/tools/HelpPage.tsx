/**
 * 幫助中心（/help，原型「幫助中心」）：搜尋、分類篩選、文章卡片；點卡片看步驟。
 */
export function HelpPage() {
  const cats = [t('help.all'), ...new Set(HELP.map((h) => h[0]))];
  const [cat, setCat] = useState(cats[0]);
  const [draft, setDraft] = useState('');
  const [key, setKey] = useState('');
  const [open, setOpen] = useState<number | null>(null);
  const list = HELP.map((h, i) => ({ h, i })).filter(({ h }) => (cat === cats[0] || h[0] === cat) && (!key || (h[1] + h[2] + h[3].join('')).includes(key)));
  const submit = (e: FormEvent) => {
    e.preventDefault();
    setKey(draft.trim());
  };
  const art = open != null ? HELP[open] : null;
  return (
    <div className="pg1">
      <section className="panel help-page">
        <div className="scroll">
          <div className="help-top">
            <h2>{t('help.welcome')}</h2>
            <form className="help-search" onSubmit={submit} role="search">
              <input value={draft} onChange={(e) => setDraft(e.target.value)} placeholder={t('help.placeholder')} aria-label={t('help.search')} />
              <button type="submit">{t('help.search')}</button>
            </form>
          </div>
          <div className="chips">
            {cats.map((c) => (
              <button key={c} type="button" className={c === cat ? 'on' : ''} aria-pressed={c === cat} onClick={() => setCat(c)}>
                {c}
              </button>
            ))}
            <span className="chips-n">{t('help.count', { n: list.length })}</span>
          </div>
          <div className="hcards">
            {list.length === 0 && <p className="empty-state">{t('help.none')}</p>}
            {list.map(({ h, i }) => (
              <button key={i} type="button" className="hcard" onClick={() => setOpen(i)}>
                <span className="cat">{h[0]}</span>
                <b>{h[1]}</b>
                <span>{h[2]}</span>
              </button>
            ))}
          </div>
        </div>
      </section>
      {art && (
        <div className="modal-bg" onKeyDown={(e) => e.key === 'Escape' && setOpen(null)}>
          <div className="modal wide2" role="dialog" aria-modal="true" aria-label={art[1]}>
            <h2>{art[1]}</h2>
            <p>{art[2]}</p>
            <ol className="steps">
              {art[3].map((s) => (
                <li key={s}>{s}</li>
              ))}
            </ol>
            <div className="row">
              <button type="button" className="btn primary" onClick={() => setOpen(null)} autoFocus>
                {t('common.close')}
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
